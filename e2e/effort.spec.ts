import AxeBuilder from '@axe-core/playwright';
import { readFile } from 'node:fs/promises';
import { SAMPLE, acceptDialogs, expect, seed, tab, test } from './fixtures';

for (const theme of ['light', 'dark'] as const) {
  test(`RIR: registrar, exportar y editar en ${theme}`, async ({ page, errors }, testInfo) => {
    void errors;
    await page.emulateMedia({ colorScheme: theme, reducedMotion: 'reduce' });
    await seed(page, SAMPLE);
    await acceptDialogs(page);
    const settings = async () => {
      await tab(page, 'Perfil').click();
      await page.getByRole('button', { name: 'Ajustes', exact: true }).click();
    };
    const audit = async () => {
      const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
      expect(result.violations).toEqual([]);
    };
    await settings();
    const scale = page.getByLabel('Escala de esfuerzo');
    await expect(scale).toHaveValue('rpe');
    await scale.focus();
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Enter');
    await expect(scale).toHaveValue('rir');
    await page.getByRole('checkbox', { name: 'Mostrar columna RIR' }).click();
    await audit();
    await page.screenshot({ path: testInfo.outputPath(`ajustes-${theme}.png`) });
    await tab(page, 'Entrenar').click();
    await page.getByRole('button', { name: 'Empezar entrenamiento vacío' }).click();
    await page.getByRole('button', { name: 'Añadir ejercicio' }).click();
    await page.getByPlaceholder('Buscar ejercicio…').fill('press de banca');
    await page.locator('.exrow', { hasText: 'Press de banca (barra)' }).first().click();
    const row = page.locator('.swipe .set').first();
    await row.getByLabel('Peso (kg)', { exact: true }).fill('60');
    await row.getByLabel('Repeticiones', { exact: true }).fill('10');
    await row.getByLabel('RIR', { exact: true }).selectOption('2');
    await expect(row.getByLabel('RIR', { exact: true }).locator('option')).toHaveText(['–', '0', '0.5', '1', '1.5', '2', '2.5', '3', '3.5', '4']);
    await row.getByLabel('Completar serie').click();
    await audit();
    await page.screenshot({ path: testInfo.outputPath(`registro-${theme}.png`) });
    await page.getByRole('button', { name: 'Terminar', exact: true }).click();
    await page.getByRole('button', { name: 'Editar', exact: true }).click();
    await expect(page.getByLabel('RIR', { exact: true }).first()).toHaveValue('2');
    await page.getByRole('button', { name: 'Guardar', exact: true }).click();
    await settings();
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Exportar entrenamientos (CSV)', exact: true }).click();
    const csv = await readFile((await (await download).path())!, 'utf8');
    expect(csv.split('\n').some((line) => line.includes('"60","10"') && line.endsWith('"8"'))).toBe(true);
    await page.getByLabel('Escala de esfuerzo').selectOption('rpe');
    await tab(page, 'Historial').click();
    await page.locator('button.hrow').first().click();
    await page.getByRole('button', { name: 'Editar', exact: true }).click();
    const rpe = page.getByLabel('RPE', { exact: true }).first();
    await expect(rpe).toHaveValue('8');
    await rpe.selectOption('8.5');
    await page.getByRole('button', { name: 'Guardar', exact: true }).click();
    await settings();
    await page.getByLabel('Escala de esfuerzo').selectOption('rir');
    await tab(page, 'Historial').click();
    await page.locator('button.hrow').first().click();
    await page.getByRole('button', { name: 'Editar', exact: true }).click();
    const rir = page.getByLabel('RIR', { exact: true }).first();
    await expect(rir).toHaveValue('1.5');
    await audit();
    await page.screenshot({ path: testInfo.outputPath(`edicion-${theme}.png`) });
    await rir.selectOption('');
    await page.getByRole('button', { name: 'Guardar', exact: true }).click();
    await page.getByRole('button', { name: 'Editar', exact: true }).click();
    await expect(page.getByLabel('RIR', { exact: true }).first()).toHaveValue('');
    await page.getByRole('button', { name: 'Guardar', exact: true }).click();
    await settings();
    await page.getByRole('checkbox', { name: 'Mostrar columna RIR' }).click();
    await tab(page, 'Historial').click();
    await page.locator('button.hrow').first().click();
    await page.getByRole('button', { name: 'Editar', exact: true }).click();
    await expect(page.getByLabel('RIR', { exact: true })).toHaveCount(0);
  });
}
